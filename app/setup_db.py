"""Destructive reset of this project's schema only; explicit CLI invocation required."""
import argparse
import hashlib
from datetime import datetime,timedelta,timezone
from psycopg import sql
from app.db import DB, SCHEMA

DDL = '''
CREATE TABLE accounts(id integer PRIMARY KEY, username text NOT NULL, salt text NOT NULL,password_hash text NOT NULL);
CREATE TABLE services(id integer PRIMARY KEY,name text NOT NULL,duration_minutes integer NOT NULL CHECK(duration_minutes>0));
CREATE TABLE specialists(id integer PRIMARY KEY,name text NOT NULL,service_id integer NOT NULL REFERENCES services(id));
CREATE TABLE slots(id integer PRIMARY KEY,specialist_id integer NOT NULL REFERENCES specialists(id),starts_at timestamptz NOT NULL,ends_at timestamptz NOT NULL,CHECK(ends_at>starts_at));
CREATE TABLE appointments(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,account_id integer NOT NULL REFERENCES accounts(id),slot_id integer NOT NULL REFERENCES slots(id),specialist_id integer NOT NULL REFERENCES specialists(id),service_id integer NOT NULL REFERENCES services(id),starts_at timestamptz NOT NULL,ends_at timestamptz NOT NULL,status text NOT NULL CHECK(status IN ('booked','cancelled')),cancelled_at timestamptz,CHECK(ends_at>starts_at),CHECK((status='cancelled')=(cancelled_at IS NOT NULL)));
'''

def seed(volume):
    ns,nv,nslots,na = (10,10,500,300) if volume=='small' else (200,30,200000,50000)
    base = datetime(2026,10,1,8,tzinfo=timezone.utc)
    salt = bytes.fromhex('c0ffee00112233445566778899aabbcc')
    with DB() as db:
        db.conn.execute(sql.SQL('DROP SCHEMA IF EXISTS {} CASCADE').format(sql.Identifier(SCHEMA)))
        db.conn.execute(sql.SQL('CREATE SCHEMA {}').format(sql.Identifier(SCHEMA)))
        db.conn.execute(DDL)
        db.conn.execute('INSERT INTO accounts VALUES(1,%s,%s,%s)',('demo',salt.hex(),hashlib.pbkdf2_hmac('sha256',b'demo',salt,100000).hex()))
        with db.conn.cursor().copy('COPY services FROM STDIN') as cp:
            for i in range(1,nv+1): cp.write_row((i,f'Услуга {i}',[30,45,60][(i-1)%3]))
        with db.conn.cursor().copy('COPY specialists FROM STDIN') as cp:
            for i in range(1,ns+1): cp.write_row((i,f'Специалист {i}',(i-1)%nv+1))
        def slot(i):
            specialist = (i-1)%ns+1
            ordinal = (i-1)//ns
            start = base+timedelta(days=ordinal//8,hours=ordinal%8)
            return specialist,start,start+timedelta(hours=1)
        with db.conn.cursor().copy('COPY slots FROM STDIN') as cp:
            for i in range(1,nslots+1):
                sp,start,end=slot(i); cp.write_row((i,sp,start,end))
        with db.conn.cursor().copy('COPY appointments(id,account_id,slot_id,specialist_id,service_id,starts_at,ends_at,status,cancelled_at) FROM STDIN') as cp:
            for i in range(1,na+1):
                sid=i if volume=='small' else ((i-1)//ns)*4*ns+(i-1)%ns+1
                sp,start,_=slot(sid); svc=(sp-1)%nv+1
                cancelled=i%7==0
                cp.write_row((i,1,sid,sp,svc,start,start+timedelta(minutes=[30,45,60][(svc-1)%3]),'cancelled' if cancelled else 'booked',start-timedelta(hours=1) if cancelled else None))
        db.conn.execute("SELECT setval(pg_get_serial_sequence('appointments','id'),%s)",(na,))
        db.conn.execute('ANALYZE')
        for table in ['accounts','services','specialists','slots','appointments']:
            print(table,db.conn.execute(sql.SQL('SELECT count(*) AS n FROM {}').format(sql.Identifier(table))).fetchone()['n'])
        digest=db.conn.execute("SELECT md5(string_agg(id||':'||slot_id||':'||status,',' ORDER BY id)) AS digest FROM appointments").fetchone()['digest']
        print('appointments digest',digest)

if __name__=='__main__':
    parser=argparse.ArgumentParser(description='Reset karina_plokhuta schema and seed deterministic data')
    parser.add_argument('volume',choices=['small','working'])
    seed(parser.parse_args().volume)
